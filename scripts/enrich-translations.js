function ensureDir(dir) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

function mergeTranslations(master, existing, override) {
  const merged = { ...master };
  // Keep existing translations where they exist
  for (const key of Object.keys(master)) {
    if (existing && existing[key] && existing[key] !== master[key]) {
      merged[key] = existing[key]; // Preserve manual translations
    }
    if (override && override[key]) {
      merged[key] = override[key]; // Apply new overrides
    }
  }
  return merged;
}

let totalFiles = 0;

// Process hi and te with full translations
for (const [lang, langTrans] of Object.entries(TRANSLATIONS)) {
  const langDir = path.join(LOCALES_DIR, lang);
  ensureDir(langDir);

  for (const ns of NAMESPACES) {
    const filePath = path.join(langDir, `${ns}.json`);
    let existing = {};
    try {
      existing = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    } catch {}

    const masterNs = MASTER[ns] || {};
    const overrideNs = langTrans[ns] || {};
    const merged = mergeTranslations(masterNs, existing, overrideNs);

    fs.writeFileSync(filePath, JSON.stringify(merged, null, 2), 'utf8');
    console.log(`✅ Updated: ${lang}/${ns}.json (${Object.keys(merged).length} keys)`);
    totalFiles++;
  }
}

