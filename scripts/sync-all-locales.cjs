const allLangs = ['en', 'hi', 'te', 'ta', 'kn', 'ml', 'mr', 'bn', 'gu', 'pa'];

// Merge dictionaries into files
for (const lang of allLangs) {
  const langDir = path.join(localesDir, lang);
  if (!fs.existsSync(langDir)) {
    fs.mkdirSync(langDir, { recursive: true });
  }

  const langData = masterTranslations[lang] || {};

  for (const [file, keys] of Object.entries(enDefaults)) {
    const filePath = path.join(langDir, file);
    let current = {};
    if (fs.existsSync(filePath)) {
      try {
        current = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      } catch {
        current = {};
      }
    }

    const specificKeys = (langData && langData[file]) ? langData[file] : {};

    // Combine with specific keys prioritized over fallback or current
    for (const [k, v] of Object.entries(keys)) {
      if (specificKeys[k]) {
        current[k] = specificKeys[k];
      } else if (!current[k] || current[k].startsWith('[')) {
        current[k] = specificKeys[k] || v;
      }
    }

    fs.writeFileSync(filePath, JSON.stringify(current, null, 2), 'utf8');
    console.log(`Updated ${lang}/${file} (${Object.keys(current).length} keys)`);
  }
}

